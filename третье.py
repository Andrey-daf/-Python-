def count_letters(text):
    """
    Подсчитывает количество каждой буквы в тексте.
    Учитывает только русские буквы в нижнем регистре.
    """
    letter_count = {}
    russian_letters = set('абвгдеёжзийклмнопрстуфхцчшщъыьэюя')

    for char in text.lower():
        if char in russian_letters:
            letter_count[char] = letter_count.get(char, 0) + 1

    return letter_count


# TODO Напишите функцию calculate_frequency

def calculate_frequency(letter_count):
    """
    Вычисляет частоту каждой буквы в тексте.
    """
    total_letters = sum(letter_count.values())
    return {letter: count/total_letters for letter, count in letter_count.items()}


